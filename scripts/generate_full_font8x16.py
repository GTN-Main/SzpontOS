def main():
    target = "kernel/src/drivers/font8x16.c"
    font = generate_vga_font()
    
    with open(target, "w") as f:
        f.write("/*\n")
        f.write(" * SzpontOS - Complete CP437 8x16 Bitmap Font Table (256 Glyphs)\n")
        f.write(" * (C) Copyright by Szpont Industries. All rights reserved.\n")
        f.write(" */\n\n")
        f.write("#include <drivers/font8x16.h>\n\n")
        f.write("const uint8_t g_font_8x16[256][16] = {\n")
        
        for i in range(256):
            bytes_str = ",".join(f"0x{b:02X}" for b in font[i])
            char_repr = ""
            if 32 <= i <= 126 and i not in (39, 92):
                char_repr = f" /* '{chr(i)}' (0x{i:02X}) */"
            elif i == 39:
                char_repr = f" /* '\\'' (0x{i:02X}) */"
            elif i == 92:
                char_repr = f" /* '\\\\' (0x{i:02X}) */"
            else:
                char_repr = f" /* 0x{i:02X} ({i}) */"
                
            f.write(f"    [{i}] = {{{bytes_str}}},{char_repr}\n")
            
        f.write("};\n")
    print(f"[OK] Zaktualizowano {target} (pełne 256 glifów CP437).")

if __name__ == "__main__":
    main()
